// package main — специальный пакет: только из него можно собрать исполняемый файл (бинарник).
// В любом другом пакете (например, "handler" или "service") запуска не будет — это библиотечный
// код, который кто-то импортирует. main — точка входа программы.
package main

import (
	// "encoding/json" — стандартная библиотека для сериализации Go-значений в JSON и обратно.
	"encoding/json"
	// "log" — простое логирование в stderr. Здесь используем только log.Fatal.
	"log"
	// "net/http" — стандартная библиотека для HTTP-сервера и клиента. Без сторонних
	// зависимостей можно поднять полноценный веб-сервер — этим мы сейчас и пользуемся.
	"net/http"
)

// healthHandler — обработчик одного HTTP-запроса.
//
// Сигнатура func(w http.ResponseWriter, r *http.Request) — это не наша прихоть, а контракт:
// именно такую сигнатуру ожидает http.HandleFunc ниже (в Go это называется типом
// http.HandlerFunc — функция такой формы автоматически подходит туда, где нужен обработчик).
//
//   - w http.ResponseWriter — сюда мы ПИШЕМ ответ: заголовки, статус-код, тело. Это интерфейс
//     (набор методов), а не конкретная структура — сервер сам передаёт то, что реализует запись
//     в сокет клиента.
//   - r *http.Request — входящий запрос: метод (GET/POST/...), путь, заголовки, тело. Указатель
//     (*http.Request), потому что структура запроса большая — копировать её на каждый вызов
//     дорого и бессмысленно, нам нужен доступ к оригиналу.
func healthHandler(w http.ResponseWriter, r *http.Request) {
	// ВАЖНО: порядок вызовов ниже принципиален.
	// HTTP-ответ отправляется клиенту по частям: сначала заголовки, потом тело. Как только ты
	// первый раз пишешь что-то в тело (через w.Write или через Encode ниже) — Go автоматически
	// отправляет накопленные к этому моменту заголовки и "замораживает" их. Установить заголовок
	// ПОСЛЕ этого момента уже нельзя — он не попадёт в ответ. Поэтому Header().Set(...) всегда
	// идёт раньше первой записи тела.
	w.Header().Set("Content-Type", "application/json")

	// Анонимная структура прямо здесь — специально для этого одного ответа, отдельный именованный
	// тип заводить незачем: она нигде больше не используется.
	// Теги `json:"status"` говорят encoding/json, как называть поле в итоговом JSON —
	// без тега поле попало бы в JSON под своим Go-именем "Status" (с большой буквы).
	resp := struct {
		Status string `json:"status"`
	}{
		Status: "ok",
	}

	// json.NewEncoder(w) — создаёт энкодер, который пишет JSON НАПРЯМУЮ в w (в сокет клиента),
	// без промежуточного []byte в памяти. .Encode(resp) сериализует resp и сразу отправляет.
	// Ошибку тут не игнорируем молча — если сериализация или запись в сеть упали, логируем.
	if err := json.NewEncoder(w).Encode(resp); err != nil {
		log.Println("healthHandler: failed to write response:", err)
	}
}

func main() {
	// http.HandleFunc регистрирует healthHandler на путь "/health" в глобальном роутере
	// стандартной библиотеки (http.DefaultServeMux). Теперь каждый запрос на "/health"
	// (любым методом — GET, POST и т.д., голый net/http не различает методы без доп. кода)
	// будет обработан нашей функцией.
	http.HandleFunc("/health", healthHandler)

	log.Println("api listening on :8080")

	// http.ListenAndServe запускает TCP-сервер на порту 8080 и блокирует текущую горутину —
	// это значит, что дальше кода в main() не будет выполняться, пока сервер работает.
	// Второй аргумент nil означает "используй http.DefaultServeMux" — тот самый роутер,
	// в который мы зарегистрировали healthHandler строкой выше.
	//
	// log.Fatal — если ListenAndServe вернул ошибку (например, порт 8080 уже занят), эта
	// функция печатает ошибку И завершает процесс с кодом 1 (вызывает os.Exit(1) внутри).
	// В отличие от log.Println, программа после log.Fatal дальше не работает.
	log.Fatal(http.ListenAndServe(":8080", nil))
}
